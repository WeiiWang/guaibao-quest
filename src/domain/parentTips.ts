/** 某個技能的「在家這樣練」；沒有就用通用建議 */
export const practiceTipsFor = (skill: string): string[] => SKILL_TIPS[skill]?.practice ?? GENERIC_PRACTICE
export const hasSkillTips = (skill: string): boolean => skill in SKILL_TIPS

/** 日期字串（YYYY-MM-DD）換成「第幾天」，用來輪流挑句子（同一天永遠同一句，隔天換一句） */
export function dayNumber(date: string): number {
  const [y, m, d] = date.split('-').map(Number)
  return Math.floor(Date.UTC(y, (m ?? 1) - 1, d ?? 1) / 86_400_000)
}

export interface DailyTip {
  text: string
  /** 這句是依哪個技能挑的；沒有最近練習就是 null（通用小提示） */
  skill: string | null
}

/**
 * 今日小提示：依孩子最近練的技能挑一句。
 * recentSkills = 最近練習的技能（越靠前越近、越常練），空陣列代表最近沒練 → 通用小提示。
 * 同一天回傳同一句；隔天輪到下一句或下一個技能。
 */
export function pickDailyTip(recentSkills: readonly string[], date: string): DailyTip {
  const day = dayNumber(date)
  const pool = recentSkills.filter((s) => s in SKILL_TIPS).slice(0, 3)
  if (pool.length === 0) return { text: GENERIC_DAILY[day % GENERIC_DAILY.length], skill: null }
  const skill = pool[day % pool.length]
  const list = SKILL_TIPS[skill].daily
  return { text: list[Math.floor(day / pool.length) % list.length], skill }
}
